vim.opt.rtp:prepend(vim.fn.getcwd())
local bootstrap = require("completion_tools.bootstrap")
bootstrap.setup({ auto_show = false, cmdline = { enabled = false } })
assert(not package.loaded.completion_tools and not package.loaded["completion_tools.sources.lsp"])
local cmp = require("completion_tools")
assert(cmp.get_lsp_capabilities().textDocument.completion.completionItem.snippetSupport)
assert(not cmp.get_status().configured)
vim.api.nvim_exec_autocmds("InsertEnter", {})
assert(cmp.get_status().configured and vim.fn.exists("#CompletionToolsBootstrap") == 0)
local generation = cmp.get_status().generation
bootstrap.ensure()
assert(cmp.get_status().generation == generation)
cmp.dispose()
print("Completion-owned bootstrap, pure capabilities and one-time first input passed")
