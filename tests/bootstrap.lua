vim.opt.rtp:prepend(vim.fn.getcwd())
local bootstrap = require("completion_tools.bootstrap")
bootstrap.setup({ auto_show = false, cmdline = { enabled = false } })
assert(not package.loaded.completion_tools and not package.loaded["completion_tools.sources.lsp"])
local capabilities = require("completion_tools.capabilities")
local base = { workspace = { configuration = true } }
local merged = capabilities.get_lsp_capabilities(base)
assert(merged.workspace.configuration and merged.textDocument.completion.completionItem.snippetSupport)
assert(base.textDocument == nil, "Capabilities must not mutate the caller table")
assert(not package.loaded.completion_tools and not package.loaded["completion_tools.ui"])
local next_caps = capabilities.get_lsp_capabilities()
merged.textDocument.completion.completionItem.snippetSupport = false
assert(next_caps.textDocument.completion.completionItem.snippetSupport, "Results must be independent")
local cmp = require("completion_tools")
assert(vim.deep_equal(cmp.get_lsp_capabilities(), next_caps))
assert(cmp.get_lsp_capabilities().textDocument.completion.completionItem.snippetSupport)
assert(not cmp.get_status().configured)
vim.api.nvim_exec_autocmds("InsertEnter", {})
assert(cmp.get_status().configured and vim.fn.exists("#CompletionToolsBootstrap") == 0)
assert(package.loaded["completion-tools"] == cmp, "First input must expose the public engine alias")
local generation = cmp.get_status().generation
bootstrap.ensure()
assert(cmp.get_status().generation == generation)
cmp.dispose()
print("Completion-owned bootstrap, pure capabilities and one-time first input passed")
